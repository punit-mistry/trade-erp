/**
 * Writes typed `convex/_generated` files WITHOUT a Convex deployment, so the
 * project can be type-checked/tested offline. `npx convex dev` / `npx convex
 * codegen` overwrite these with the official output — the shapes match.
 *
 * Usage: node scripts/gen-convex-stubs.mjs
 */
import { mkdirSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";

const root = join(process.cwd(), "convex");
const out = join(root, "_generated");
mkdirSync(out, { recursive: true });

const EXCLUDE = new Set(["schema.ts", "auth.config.ts", "convex.config.ts"]);
const modules = [];
(function walk(dir) {
  for (const name of readdirSync(dir).sort()) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) {
      if (name === "_generated" || name.startsWith(".") || name === "__tests__") continue;
      walk(full);
      continue;
    }
    if (!/\.(ts|tsx|js)$/.test(name) || name.endsWith(".d.ts") || /\.test\.(ts|tsx|js)$/.test(name)) continue;
    const rel = relative(root, full).split(sep).join("/");
    if (EXCLUDE.has(rel)) continue;
    modules.push(rel.replace(/\.(ts|tsx|js)$/, ""));
  }
})(root);

const ident = (m) => m.replace(/[^a-zA-Z0-9]/g, "_");
const header = `/* eslint-disable */\n/**\n * Generated by scripts/gen-convex-stubs.mjs (offline stub).\n * Replaced by \`npx convex dev\` / \`npx convex codegen\`.\n */\n\n`;

writeFileSync(
  join(out, "api.d.ts"),
  header +
    modules.map((m) => `import type * as ${ident(m)} from "../${m}.js";`).join("\n") +
    `\n\nimport type { ApiFromModules, FilterApi, FunctionReference } from "convex/server";\n\n` +
    `declare const fullApi: ApiFromModules<{\n` +
    modules.map((m) => `  ${JSON.stringify(m)}: typeof ${ident(m)};`).join("\n") +
    `\n}>;\n\nexport declare const api: FilterApi<typeof fullApi, FunctionReference<any, "public">>;\n` +
    `export declare const internal: FilterApi<typeof fullApi, FunctionReference<any, "internal">>;\n` +
    `export declare const components: {};\n`,
);

writeFileSync(
  join(out, "api.js"),
  header + `import { anyApi, componentsGeneric } from "convex/server";\n\nexport const api = anyApi;\nexport const internal = anyApi;\nexport const components = componentsGeneric();\n`,
);

writeFileSync(
  join(out, "dataModel.d.ts"),
  header +
    `import type { DataModelFromSchemaDefinition, DocumentByName, TableNamesInDataModel, SystemTableNames } from "convex/server";\n` +
    `import type { GenericId } from "convex/values";\nimport schema from "../schema.js";\n\n` +
    `export type TableNames = TableNamesInDataModel<DataModel>;\n` +
    `export type Doc<TableName extends TableNames> = DocumentByName<DataModel, TableName>;\n` +
    `export type Id<TableName extends TableNames | SystemTableNames> = GenericId<TableName>;\n` +
    `export type DataModel = DataModelFromSchemaDefinition<typeof schema>;\n`,
);

writeFileSync(
  join(out, "server.d.ts"),
  header +
    `import {\n  ActionBuilder, HttpActionBuilder, MutationBuilder, QueryBuilder,\n  GenericActionCtx, GenericMutationCtx, GenericQueryCtx, GenericDatabaseReader, GenericDatabaseWriter,\n} from "convex/server";\nimport type { DataModel } from "./dataModel.js";\n\n` +
    `export declare const query: QueryBuilder<DataModel, "public">;\n` +
    `export declare const internalQuery: QueryBuilder<DataModel, "internal">;\n` +
    `export declare const mutation: MutationBuilder<DataModel, "public">;\n` +
    `export declare const internalMutation: MutationBuilder<DataModel, "internal">;\n` +
    `export declare const action: ActionBuilder<DataModel, "public">;\n` +
    `export declare const internalAction: ActionBuilder<DataModel, "internal">;\n` +
    `export declare const httpAction: HttpActionBuilder;\n\n` +
    `export type QueryCtx = GenericQueryCtx<DataModel>;\nexport type MutationCtx = GenericMutationCtx<DataModel>;\nexport type ActionCtx = GenericActionCtx<DataModel>;\n` +
    `export type DatabaseReader = GenericDatabaseReader<DataModel>;\nexport type DatabaseWriter = GenericDatabaseWriter<DataModel>;\n`,
);

writeFileSync(
  join(out, "server.js"),
  header +
    `import {\n  actionGeneric, httpActionGeneric, queryGeneric, mutationGeneric,\n  internalActionGeneric, internalMutationGeneric, internalQueryGeneric,\n} from "convex/server";\n\n` +
    `export const query = queryGeneric;\nexport const internalQuery = internalQueryGeneric;\nexport const mutation = mutationGeneric;\nexport const internalMutation = internalMutationGeneric;\nexport const action = actionGeneric;\nexport const internalAction = internalActionGeneric;\nexport const httpAction = httpActionGeneric;\n`,
);

console.log(`convex/_generated stubs written for ${modules.length} modules.`);
